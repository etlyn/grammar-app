export function enrichChapter(topic) {
  const n = notes[topic.slug];
  if (!n) return topic;
  const [intro, patterns, paragraphs, examples, edge] = n;
  const rules = topic.rules.map((r, i) => ({
    ...r,
    pattern: patterns[i],
    paragraphs: [paragraphs[i]],
    examples: r.examples.concat(examples[i] ? [examples[i]] : []),
  }));
  rules.push({
    title: "Contrasts and edge cases",
    explanation: edge,
    examples: examples,
  });
  return {
    ...topic,
    chapter: { introduction: [intro], rules, recap: patterns },
  };
}
